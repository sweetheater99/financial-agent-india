def _sig_default(cls, param: str):
    """Return the default value for a constructor parameter."""
    sig = inspect.signature(cls.__init__)
    p = sig.parameters.get(param)
    if p is None or p.default is inspect.Parameter.empty:
        raise KeyError(f"{cls.__name__}.__init__ has no param '{param}'")
    return p.default


