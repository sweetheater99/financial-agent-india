def _repr_value(v) -> str:
    """Format a value for code generation, preserving dict/None types."""
    if v is None:
        return "None"
    if isinstance(v, dict):
        inner = ", ".join(f'"{k}": {_repr_value(val)}' for k, val in v.items())
        return "{" + inner + "}"
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        return repr(v)
    return repr(v)


def generate_baseline_source(cfg_dict: dict) -> str:
    """Render baseline.py source from the config dict."""
    lines = [
        '"""',
        "baseline.py — Autoresearch baseline configuration.",
        "",
        "AUTO-GENERATED by autoresearch/seed_baseline.py.",
        "Do NOT edit by hand; re-run seed_baseline.py to refresh from source.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "",
        "def get_strategy_config() -> dict:",
        '    """Return the full baseline parameter dict."""',
        "    return {",
    ]

    section_comments = {
        "rsi_period": "# Signal parameters (Tier 1)",
        "futures_score_threshold": "# Entry / exit logic (Tier 2)",
        "cash_trigger_vix": "# Regime & allocation (Tier 3)",
        "custom_signal_fn": "# Custom logic hooks (Tier 4) — None = use built-in defaults",
    }

    for key, val in cfg_dict.items():
        if key in section_comments:
            lines.append(f"        {section_comments[key]}")
        lines.append(f"        {repr(key)}: {_repr_value(val)},")

    lines.append("    }")
    lines.append("")
    return "\n".join(lines)


def main():
    cfg_dict = build_config()
    src = generate_baseline_source(cfg_dict)

    out_path = os.path.join(ROOT, "autoresearch", "baseline.py")
    with open(out_path, "w") as fh:
        fh.write(src)

    print(f"Written: {out_path}")
    print(f"Keys:    {len(cfg_dict)}")

    # Quick sanity: re-import and spot-check a few values
    import importlib.util
    spec = importlib.util.spec_from_file_location("baseline", out_path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    loaded = mod.get_strategy_config()
    assert loaded["futures_score_threshold"] == strat.ENTRY_SCORE_THRESHOLD, "score_threshold mismatch"
    assert loaded["condor_min_vix"] == cfg.CONDOR_MIN_VIX, "condor_min_vix mismatch"
    print("Sanity checks passed.")


if __name__ == "__main__":
    main()
